import { describe, expect, it } from "vitest";

import { toCalendarDate } from "./Tasks";

/**
 * Срез «На сегодня» не находил ничего никогда.
 *
 * Сервер отдаёт срок задачи МЕТКОЙ ВРЕМЕНИ («2026-08-10T14:30:00Z»), а срез
 * сравнивал её со строкой сегодняшней даты («2026-08-10»). Строка из двадцати
 * символов никогда не равна строке из десяти, поэтому вкладка была пустой при
 * любых данных — и выглядело это как «на сегодня задач нет».
 */
describe("срок задачи приводится к календарной дате", () => {
  it("отрезает время у метки времени", () => {
    expect(toCalendarDate("2026-08-10T14:30:00Z")).toBe("2026-08-10");
    expect(toCalendarDate("2026-08-10T00:00:00+05:00")).toBe("2026-08-10");
  });

  it("оставляет чистую дату как есть", () => {
    expect(toCalendarDate("2026-08-10")).toBe("2026-08-10");
  });

  it("не сдвигает дату на сутки", () => {
    // Именно это сделал бы разбор через Date в поясе западнее нуля:
    // «2026-08-10T00:00:00Z» стало бы 9 августа. Срок задачи — календарный
    // день, назначенный человеком, а не момент времени.
    expect(toCalendarDate("2026-08-10T00:00:00Z")).toBe("2026-08-10");
    expect(toCalendarDate("2026-08-10T23:59:59Z")).toBe("2026-08-10");
  });

  it("возвращает null на пустом значении", () => {
    expect(toCalendarDate(null)).toBeNull();
    expect(toCalendarDate(undefined)).toBeNull();
    expect(toCalendarDate("")).toBeNull();
  });

  it("сравнение с сегодняшней датой теперь совпадает", () => {
    const today = new Date().toLocaleDateString("en-CA");
    const fromServer = `${today}T09:15:00Z`;

    // До исправления это выражение было false при любых данных.
    expect(toCalendarDate(fromServer) === today).toBe(true);
  });
});
